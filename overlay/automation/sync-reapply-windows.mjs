#!/usr/bin/env node
/**
 * sync-reapply-windows.mjs — regenerate config/profile.yml's `re_apply_windows`
 * block from the tracker, so the scanner stops re-surfacing roles at companies
 * already applied to.
 *
 * FORK-LOCAL: declared in config/local-paths.txt. Not shipped upstream.
 *
 * WHY THIS EXISTS
 * scan.mjs reads `re_apply_windows` (loadReApplyWindows/buildCooldownFilter),
 * but it is a PER-COMPANY map that each entry must carry a `last_apply_date`
 * for — there is no global "cool down for N days" setting, and an entry with a
 * missing or malformed date is silently dropped rather than warned about. Kept
 * by hand that list rots immediately: the whole point is to protect a decision
 * made months later, which is exactly when nobody remembers to update a YAML
 * block. This derives it from data/applications.md, which is already the
 * canonical record of what was applied to and when.
 *
 * WHAT COUNTS AS APPLIED
 * Any tracker row whose status is at or past `Applied` in the canonical
 * lifecycle (Applied / Responded / Interview / Offer / Hired / Rejected).
 * Evaluated / Discarded / SKIP are NOT applications and are ignored.
 * Rejected still counts: a rejection is precisely when you do not want the
 * same role resurfacing next week.
 *
 * WHAT IT WRITES
 * Only the region between the two marker comments below; everything else in
 * profile.yml is preserved byte-for-byte. Idempotent. Never edits any other
 * key, and never invents a date — a row with an unparseable date is skipped
 * and reported, not guessed at.
 *
 * Run: node automation/sync-reapply-windows.mjs [--dry-run]
 *      [--same-role-days N] (default 180)
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { dirname, join, resolve, relative, isAbsolute } from 'path';
import { fileURLToPath } from 'url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PROFILE = join(ROOT, 'config/profile.yml');

/** Repo-relative when the path is inside the checkout, absolute otherwise —
 *  a blind slice(ROOT.length) mangles any path outside it (e.g. a fixture). */
const displayPath = (p) => {
  const rel = relative(ROOT, p);
  return !rel || rel.startsWith('..') || isAbsolute(rel) ? p : rel;
};

const argv = process.argv.slice(2);
const DRY_RUN = argv.includes('--dry-run');
const numFlag = (name, dflt) => {
  const i = argv.indexOf(name);
  if (i === -1) return dflt;
  const n = Number(argv[i + 1]);
  return Number.isInteger(n) && n >= 0 ? n : dflt;
};
const SAME_ROLE_DAYS = numFlag('--same-role-days', 180);
// NOTE: `cross_role_bucket` is deliberately NOT generated. scan.mjs matches it
// by splitting the bucket name into keywords and testing them against job
// titles, after discarding generic words — deriving one automatically would
// guess at which roles you consider interchangeable. Add it by hand inside the
// generated block if you want it (this script overwrites the block, so put a
// hand-written bucket in its own entry outside the markers instead).

const BEGIN = '# >>> re_apply_windows: generated by automation/sync-reapply-windows.mjs — do not edit by hand';
const END = '# <<< end generated re_apply_windows';

// Statuses at or past "Applied" in templates/states.yml's lifecycle.
const APPLIED_STATES = new Set(['applied', 'responded', 'interview', 'offer', 'hired', 'rejected']);

function resolveTrackerPath() {
  const env = process.env.CAREER_OPS_TRACKER?.trim();
  if (env) return resolve(ROOT, env);
  const nested = join(ROOT, 'data/applications.md');
  return existsSync(nested) ? nested : join(ROOT, 'applications.md');
}

/** Parse the tracker's markdown table by column NAME, never by position. */
function readTrackerRows(path) {
  if (!existsSync(path)) return [];
  const lines = readFileSync(path, 'utf-8').split(/\r?\n/);
  let cols = null;
  const rows = [];

  for (const line of lines) {
    if (!line.trim().startsWith('|')) continue;
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells.length === 0) continue;

    if (!cols) {
      const lowered = cells.map((c) => c.toLowerCase().replace(/^#$/, 'num'));
      if (lowered.includes('company') && lowered.includes('status')) {
        cols = Object.fromEntries(lowered.map((name, i) => [name, i]));
      }
      continue;
    }
    if (/^:?-+:?$/.test(cells[0])) continue; // separator row

    const get = (name) => (cols[name] !== undefined ? cells[cols[name]] ?? '' : '');
    const company = get('company');
    const status = get('status').toLowerCase().replace(/\*/g, '').trim();
    if (!company || company === '?') continue;
    rows.push({ company, role: get('role'), status, date: get('date') });
  }
  return rows;
}

const tracker = resolveTrackerPath();
const rows = readTrackerRows(tracker).filter((r) => APPLIED_STATES.has(r.status));

// company -> { lastApplyDate, roles:Set }
const byCompany = new Map();
const skipped = [];
for (const r of rows) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date) || Number.isNaN(Date.parse(r.date))) {
    skipped.push(`${r.company} — unparseable date "${r.date}"`);
    continue;
  }
  const cur = byCompany.get(r.company) || { lastApplyDate: r.date, roles: new Set() };
  if (r.date > cur.lastApplyDate) cur.lastApplyDate = r.date;
  if (r.role) cur.roles.add(r.role);
  byCompany.set(r.company, cur);
}

const yamlQuote = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

let block;
if (byCompany.size === 0) {
  block = [
    BEGIN,
    '# No applications recorded yet — nothing to cool down. This block repopulates',
    '# automatically once a tracker row reaches Applied (or beyond).',
    '# re_apply_windows: {}',
    END,
  ].join('\n');
} else {
  const lines = [
    BEGIN,
    `# Derived from ${displayPath(tracker)} — rerun after any status change.`,
    `# same_role_days=${SAME_ROLE_DAYS}`,
    're_apply_windows:',
  ];
  for (const [company, info] of [...byCompany].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`  ${yamlQuote(company)}:`);
    lines.push(`    last_apply_date: "${info.lastApplyDate}"`);
    lines.push(`    same_role_days: ${SAME_ROLE_DAYS}`);
    if (info.roles.size > 0) {
      lines.push(`    applied_to: [${[...info.roles].map(yamlQuote).join(', ')}]`);
    }
  }
  lines.push(END);
  block = lines.join('\n');
}

if (!existsSync(PROFILE)) {
  console.error(`sync-reapply-windows: ${PROFILE} not found`);
  process.exit(1);
}

const original = readFileSync(PROFILE, 'utf-8');
const startIdx = original.indexOf(BEGIN);
const endIdx = original.indexOf(END);

let updated;
if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
  updated = original.slice(0, startIdx) + block + original.slice(endIdx + END.length);
} else if (startIdx !== -1 || endIdx !== -1) {
  console.error('sync-reapply-windows: only one marker found — refusing to guess the region. Fix config/profile.yml by hand.');
  process.exit(1);
} else {
  const sep = original.endsWith('\n') ? '\n' : '\n\n';
  updated = original + sep + block + '\n';
}

for (const s of skipped) console.warn(`  ⚠️  skipped: ${s}`);

if (updated === original) {
  console.log(`sync-reapply-windows: already up to date (${byCompany.size} company/companies)`);
  process.exit(0);
}

if (DRY_RUN) {
  console.log('sync-reapply-windows: would write this block:\n');
  console.log(block);
  process.exit(0);
}

writeFileSync(PROFILE, updated, 'utf-8');
console.log(`sync-reapply-windows: updated ${displayPath(PROFILE)} — ${byCompany.size} company/companies under cooldown`);
